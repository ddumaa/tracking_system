package com.project.tracking_system.dto;

/**
 * Перечисление кодов ошибок REST-API возвратов.
 * <p>
 * Значения используются фронтендом для отображения типовых сценариев ошибок,
 * поэтому должны оставаться стабильными и согласованными с контрактом.
 * </p>
 */
public enum ReturnApiErrorCode {
    /** Действие недоступно в текущем состоянии заявки. */
    ACTION_NOT_ALLOWED,
    /** Запрошенная сущность не найдена. */
    ENTITY_NOT_FOUND,
    /** Пользователь не имеет прав на выполнение операции. */
    FORBIDDEN,
    /** Нарушен оптимистичный контроль версий данных. */
    OPTIMISTIC_LOCK,
    /** Обнаружен конфликт идемпотентности. */
    IDEMPOTENCY_CONFLICT,
    /** Входные данные не прошли валидацию. */
    VALIDATION_FAILED
}
